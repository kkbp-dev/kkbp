def deform_vertex_groups(build):
    for bone in UNCONSTRAINED:
        constraints.clear(build.metarig, bone)
    parts = build.meshes()
    for old, new in VERTEX_GROUPS:
        meshes.rename_group(parts, old, new)
    if build.features.skirt:
        for chain in range(8):
            for i in range(6):
                meshes.rename_group(parts, names.skirt_bone(False, chain, i), names.skirt_deform_bone(chain, i))
