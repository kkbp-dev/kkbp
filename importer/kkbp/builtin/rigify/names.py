"""Every name the Rigify Hook gives or looks for, exactly as the rig has always had it.

The rig keeps the legacy importer's names (ADR 0023): people animate with its controls, saved actions
name them, and the legacy documentation and retargeting lists use them. So every string here stays
byte for byte; a name built from parts (`DEFORM_BONE_PREFIX + LEFT_ARM_BONE`) stays built from them,
so the relation shows.

The bone names are of three kinds:

- the readable names prepare.py gives the bones with a Bone Role before the Hook runs (D23,
  bone_names.py), such as "Left arm" and "Thumb0_L"
- names of bones the Hook makes itself, such as "Eyes handle" and "Breasts handle";
- game names (`cf_...`) of bones with no Bone Role, found by exact name because no Role or Group
  tells them apart. docs/design/hooks-and-tools.md lists them.

Right-side names come from left-side ones through `right_name`.
"""

# --- Name parts ---------------------------------------------------------------------------
METARIG_ID_BONE_PREFIX = "Metarig_ID:"
LEFT_NAME_PREFIX = "Left "
RIGHT_NAME_PREFIX = "Right "
LEFT_NAME_SUFFIX1 = "_L"
RIGHT_NAME_SUFFIX1 = "_R"
LEFT_NAME_SUFFIX2 = ".L"
RIGHT_NAME_SUFFIX2 = ".R"
COPY_NAME_SUFFIX = " copy"
RENAMED_NAME_SUFFIX = " renamed"


def right_name(left):
    """The right-side name of a left-side one: "Left " becomes "Right ", and a final "_L" or ".L"
    becomes "_R" or ".R"."""
    name = left
    if name.startswith(LEFT_NAME_PREFIX):
        name = RIGHT_NAME_PREFIX + name[len(LEFT_NAME_PREFIX):]
    if name.endswith(LEFT_NAME_SUFFIX1):
        name = name[:-len(LEFT_NAME_SUFFIX1)] + RIGHT_NAME_SUFFIX1
    if name.endswith(LEFT_NAME_SUFFIX2):
        name = name[:-len(LEFT_NAME_SUFFIX2)] + RIGHT_NAME_SUFFIX2
    return name


