"""Writes the node groups and materials of a .blend as builder modules (docs/design/library-from-code.md).

    blender --background --factory-startup FILE.blend --python importer/tools/library/export_nodes.py -- OUT_DIR [NAME ...]

Writes `OUT_DIR/groups/<module>.py` per node group and `OUT_DIR/materials/<module>.py` per material,
all of them or only the NAMEs given. Run through `scripts/export-library-nodes.sh`, which writes into
`importer/tools/library/`, after editing a group in Blender: the module then matches the file, and the
diff shows what the edit changed.

Each node is written with the properties that differ from a fresh node of its type, its socket
values that differ from a fresh node's, and its hidden sockets; links by socket identifier, or by
interface socket name (by position where a name repeats) on group nodes. A module only builds; which
file a datablock goes into, and its fake user and version, is `build.py`'s.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

import bpy
import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
from introspect import GROUP_LIKE, diff, same  # noqa: E402

GENERATED = "generated by export_nodes.py from {source}; kept by hand from then on"

# Properties written by other means, derived by Blender, or only for the UI.
_NODE_SKIP = {"rna_type", "enum_items", "enum_definition", "active_index", "active_item", "name", "inputs", "outputs", "internal_links", "parent", "select", "dimensions",
              "type", "bl_idname", "bl_label", "bl_description", "bl_icon", "bl_static_type", "bl_width_default",
              "bl_width_min", "bl_width_max", "bl_height_default", "bl_height_min", "bl_height_max",
              "color_ramp", "mapping", "location_absolute", "is_active_output", "interface", "warning_propagation",
              "panel_states"}
_ITEM_SKIP = {"rna_type", "select", "identifier", "item_type", "in_out", "name", "parent", "position", "index", "bl_socket_idname",
              "socket_type", "interface_items"}
_MATERIAL_SKIP = {"rna_type", "name", "name_full", "node_tree", "use_nodes", "grease_pencil", "paint_active_slot",
                  "texture_paint_images", "texture_paint_slots", "preview", "animation_data", "use_fake_user",
                  "is_grease_pencil", "is_editable", "is_linked_packed", "is_evaluated", "original", "users",
                  "session_uid", "tag", "is_runtime_data", "is_missing", "is_embedded_data", "use_extra_user",
                  "library", "library_weak_reference", "override_library", "asset_data", "id_type",
                  "is_library_indirect", "paint_clone_slot", "line_priority"}
_TREE_SKIP = _MATERIAL_SKIP | {"nodes", "links", "interface", "bl_idname", "bl_label", "bl_description", "bl_icon",
                               "bl_use_group_interface", "type", "is_modifier", "is_tool", "grease_pencil",
                               "view_center", "is_mode_object", "is_mode_edit", "is_mode_sculpt", "is_mode_paint",
                               "is_type_mesh", "is_type_curve", "is_type_point_cloud", "is_type_grease_pencil",
                               "is_type_volume"}


# --- values ------------------------------------------------------------------------------

def lit(v):
    """A property value as Python source."""
    if isinstance(v, bpy.types.ID):
        kind = {"Image": "image", "ShaderNodeTree": "group", "GeometryNodeTree": "group", "Object": "obj",
                "Material": "material", "Text": "text"}.get(type(v).__name__)
        if kind is None:
            raise TypeError(f"no reference for {type(v).__name__} {v.name}")
        return f"lib.{kind}({v.name!r})"
    if isinstance(v, float):
        return f32(v)
    if isinstance(v, (bool, int, str)) or v is None:
        return repr(v)
    if isinstance(v, (set, frozenset)):
        return repr(set(sorted(v))) if v else "set()"
    try:
        items = list(v)
    except TypeError:
        return repr(v)
    if items and hasattr(items[0], "__len__") and not isinstance(items[0], str):
        return "(" + ", ".join(lit(x) for x in items) + ("," if len(items) == 1 else "") + ")"
    return "(" + ", ".join(lit(x) for x in items) + ("," if len(items) == 1 else "") + ")"


def f32(v):
    """The shortest decimal that reads back as the same float32: Blender stores floats as float32."""
    if v != v or v in (float("inf"), float("-inf")):
        return f"float({str(v)!r})"
    text = str(np.float32(v))
    if float(np.float32(float(text))) != float(np.float32(v)):
        return repr(v)
    return text if any(c in text for c in ".en") else text + ".0"


def props_source(d, indent):
    if not d:
        return "{}"
    pad = " " * (indent + 4)
    parts = []
    for k, v in d.items():
        parts.append(f"{pad}{k!r}: {props_source(v, indent + 4) if isinstance(v, dict) else lit(v)},")
    return "{\n" + "\n".join(parts) + "\n" + " " * indent + "}"


# --- sockets -----------------------------------------------------------------------------

def socket_key(s, sockets):
    if s.node.bl_idname in GROUP_LIKE:
        same_name = [x for x in sockets if x.name == s.name]
        if s.name and len(same_name) == 1:
            return repr(s.name)
        return str(list(sockets).index(s))
    return repr(s.identifier)


# --- trees --------------------------------------------------------------------------------

class Scratch:
    """Fresh nodes and sockets to compare against, one tree per kind."""

    def __init__(self):
        self.trees = {}

    def tree(self, kind):
        if kind not in self.trees:
            self.trees[kind] = bpy.data.node_groups.new("~scratch", kind)
        return self.trees[kind]

    def pristine(self, kind, n):
        return self.tree(kind).nodes.new(n.bl_idname)

    def node(self, kind, n):
        """A fresh node set up like `n` (enums, group), so its sockets are `n`'s."""
        t = self.tree(kind)
        f = t.nodes.new(n.bl_idname)
        for name in ("data_type", "domain", "input_type", "mode", "operation", "blend_type", "factor_mode",
                     "vector_type", "space"):
            if hasattr(n, name) and hasattr(f, name):
                try:
                    setattr(f, name, getattr(n, name))
                except Exception:  # noqa: BLE001
                    pass
        if getattr(n, "node_tree", None) is not None:
            f.node_tree = n.node_tree
        if getattr(n, "enum_items", None) is not None:
            f.enum_items.clear()
            for e in n.enum_items:
                f.enum_items.new(e.name)
        return f

    def item(self, kind, item):
        t = self.tree(kind)
        if item.item_type == "PANEL":
            return t.interface.new_panel("~")
        return t.interface.new_socket(name="~", in_out=item.in_out, socket_type=item.socket_type)

    def clear(self):
        for t in self.trees.values():
            t.nodes.clear()
            t.interface.clear()


def tree_lines(tree, kind, scratch):
    lines = []
    for item in tree.interface.items_tree:
        parent = item.parent.name if item.parent and item.parent.parent else None
        extra = diff(item, scratch.item(kind, item), _ITEM_SKIP, depth=0)
        if parent is not None:
            extra = {"parent": parent, **extra}
        args = ", ".join(f"{k}={lit(v)}" for k, v in extra.items())
        if item.item_type == "PANEL":
            lines.append(f"t.panel({item.name!r}{', ' + args if args else ''})")
        else:
            lines.append(f"t.socket({item.in_out!r}, {item.name!r}, {item.socket_type!r}{', ' + args if args else ''})")
    if lines:
        lines.append("")

    # Frames before the nodes in them, outer frames first.
    def depth(n):
        d = 0
        while n.parent is not None:
            n, d = n.parent, d + 1
        return d
    ordered = sorted(tree.nodes, key=lambda n: (n.bl_idname != "NodeFrame", depth(n) if n.bl_idname == "NodeFrame" else 0))
    for n in ordered:
        fresh = scratch.node(kind, n)
        args = [repr(n.bl_idname), repr(n.name)]
        if n.parent is not None:
            args.append(f"parent={n.parent.name!r}")
        # A reroute draws at a fixed size whatever its width says.
        props = diff(n, scratch.pristine(kind, n), _NODE_SKIP | ({"width"} if n.bl_idname == "NodeReroute" else set()))
        if getattr(n, "node_tree", None) is not None:  # the scratch node has it too, so diff misses it
            props = {"node_tree": n.node_tree, **props}
        props.setdefault("location", tuple(n.location))
        if getattr(n, "enum_items", None) is not None:
            args.append("enum_items=" + repr([(e.name, e.description) for e in n.enum_items]))
        if getattr(n, "is_active_output", None) is not None and "is_active_output" not in props:
            if n.is_active_output != fresh.is_active_output:
                props["is_active_output"] = n.is_active_output
        for name, sockets, fresh_sockets in (("inputs", n.inputs, fresh.inputs), ("outputs", n.outputs, fresh.outputs)):
            values = {}
            hidden = []
            # Values that mirror the interface, or a reroute's, which pass their link on.
            interface_node = n.bl_idname in ("NodeGroupInput", "NodeGroupOutput", "NodeReroute")
            for i, s in enumerate(sockets):
                f = _match(s, i, fresh_sockets)
                if (hasattr(s, "default_value") and not interface_node
                        and (f is None or not same(s.default_value, f.default_value))):
                    values[socket_key(s, sockets)] = lit(s.default_value)
                if s.hide and (f is None or not f.hide):
                    hidden.append(socket_key(s, sockets))
            if values:
                args.append(f"{name}={{" + ", ".join(f"{k}: {v}" for k, v in values.items()) + "}")
            if hidden:
                args.append(f"hide_{name}=(" + ", ".join(hidden) + ("," if len(hidden) == 1 else "") + ")")
        if getattr(n, "color_ramp", None) is not None:
            r = n.color_ramp
            elements = ", ".join(f"{{'position': {f32(e.position)}, 'color': {lit(e.color)}}}" for e in r.elements)
            args.append(f"color_ramp={{'color_mode': {r.color_mode!r}, 'interpolation': {r.interpolation!r}, "
                        f"'hue_interpolation': {r.hue_interpolation!r}, 'elements': [{elements}]}}")
        if getattr(n, "mapping", None) is not None:
            m = n.mapping
            curves = ", ".join("{'points': [" + ", ".join(f"{{'location': {lit(p.location)}, 'handle_type': {p.handle_type!r}}}"
                                                          for p in c.points) + "]}" for c in m.curves)
            args.append("mapping={" + ", ".join(f"{k!r}: {lit(getattr(m, k))}" for k in (
                "extend", "use_clip", "clip_min_x", "clip_min_y", "clip_max_x", "clip_max_y", "black_level",
                "white_level", "tone")) + f", 'curves': [{curves}]}}")
        lines.append(f"t.node({', '.join(args)}, props={props_source(props, 0)})")
    lines.append("")
    for l in tree.links:
        a = socket_key(l.from_socket, l.from_node.outputs)
        b = socket_key(l.to_socket, l.to_node.inputs)
        muted = ", muted=True" if l.is_muted else ""
        lines.append(f"t.link({l.from_node.name!r}, {a}, {l.to_node.name!r}, {b}{muted})")
    ad = tree.animation_data
    if ad is not None and ad.drivers:
        lines.append("")
        for fc in ad.drivers:
            lines.append(driver_line(fc))
    scratch.clear()
    return lines


def _match(s, i, fresh_sockets):
    if s.node.bl_idname in GROUP_LIKE:
        f = fresh_sockets[i] if i < len(fresh_sockets) else None
        return f if f is not None and f.bl_idname == s.bl_idname else None
    return next((f for f in fresh_sockets if f.identifier == s.identifier), None)


def driver_line(fc):
    d = fc.driver
    variables = []
    counts = {"SINGLE_PROP": 1, "TRANSFORMS": 1, "CONTEXT_PROP": 1}
    for v in d.variables:
        targets = []
        for t in list(v.targets)[:counts.get(v.type, 2)]:
            data = {}
            if v.type == "SINGLE_PROP":
                data["id_type"] = t.id_type
            if t.id is not None:
                data["id"] = t.id.name
            for name in ("data_path", "bone_target", "transform_type", "transform_space", "rotation_mode"):
                value = getattr(t, name)
                if value not in ("", None):
                    data[name] = value
            targets.append(data)
        variables.append(f"({v.name!r}, {v.type!r}, {targets!r})")
    extra = ""
    if fc.array_index:
        extra += f", index={fc.array_index}"
    if d.type != "SCRIPTED":
        extra += f", type={d.type!r}"
    if d.use_self:
        extra += ", use_self=True"
    if variables:
        extra += ", variables=[" + ", ".join(variables) + "]"
    return f"t.driver({fc.data_path!r}, {d.expression!r}{extra})"


# --- modules ----------------------------------------------------------------------------

def module_name(name):
    s = re.sub(r"[^0-9a-zA-Z]+", "_", name).strip("_").lower()
    return ("_" + s) if s[:1].isdigit() else s


def write(path, name, kind, body, source, header_extra=""):
    head = f"NAME = {name!r}\n" + (f"{header_extra}\n" if header_extra else "")
    text = (f'"""`{name}`: {GENERATED.format(source=source)}."""\n\n{head}\n\n'
            f"def build(lib):\n" + "\n".join(("    " + l) if l else "" for l in "\n".join(body).split("\n")) + "\n")
    path.write_text(text)


def main():
    args = sys.argv[sys.argv.index("--") + 1:]
    out, names = Path(args[0]), set(args[1:])
    source = Path(bpy.data.filepath).name
    scratch = Scratch()
    written = {}
    groups = [g for g in bpy.data.node_groups if not names or g.name in names]
    materials = [m for m in bpy.data.materials if m.node_tree and (not names or m.name in names)]
    for folder, items in (("groups", groups), ("materials", materials)):
        (out / folder).mkdir(parents=True, exist_ok=True)
        for item in items:
            module = module_name(item.name)
            if (folder, module) in written:
                raise RuntimeError(f"{item.name!r} and {written[folder, module]!r} both make {module}.py")
            written[folder, module] = item.name
            if folder == "groups":
                head = [f"t = lib.new_group(NAME, KIND, props={props_source(diff(item, scratch.tree(item.bl_idname), _TREE_SKIP, depth=0), 4)})", ""]
                body = head + tree_lines(item, item.bl_idname, scratch) + ["return t"]
                write(out / folder / f"{module}.py", item.name, item.bl_idname, body, source, f"KIND = {item.bl_idname!r}")
            else:
                fresh = bpy.data.materials.new("~scratch")
                head = [f"t = lib.new_material(NAME, props={props_source(diff(item, fresh, _MATERIAL_SKIP, depth=0), 4)})", ""]
                bpy.data.materials.remove(fresh)
                body = head + tree_lines(item.node_tree, "ShaderNodeTree", scratch) + ["return t"]
                write(out / folder / f"{module}.py", item.name, "material", body, source)
    print(f"Wrote {len(groups)} groups and {len(materials)} materials into {out}")


main()
