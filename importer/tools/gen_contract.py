"""Generates importer/kkbp/bundle/_contract.py from the contract's JSON Schemas.

    python3 importer/tools/gen_contract.py          # rewrite the module
    python3 importer/tools/gen_contract.py --check  # exit 1 if it is out of date

The add-on can't read contract/ at runtime, so the closed sets it checks bundles against are
copied into a Python module. A bundle/ test fails when the copy and the schemas disagree.
"""

import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SCHEMA = REPO / "contract" / "schema"
TARGET = REPO / "importer" / "kkbp" / "bundle" / "_contract.py"

# Constant name -> set schema file under contract/schema/sets/.
SETS = {
    "BONE_ROLES": "bone-role",
    "BONE_GROUPS": "bone-group",
    "MATERIAL_ROLES": "material-role",
    "BLEND_MODES": "blend-mode",
    "TEXTURE_ROLES": "texture-role",
    "TEXTURE_VARIANTS": "texture-variant",
    "EXPRESSION_CATEGORIES": "expression-category",
    "EXPRESSION_NAMES": "expression-name",
}


def render():
    common = _load(SCHEMA / "common.schema.json")
    version = re.search(r"/(\d+)\.(\d+)/", _load(SCHEMA / "manifest.schema.json")["$id"])
    lines = [
        '"""The Export Bundle contract\'s closed sets, copied from contract/schema/.',
        "",
        "Generated by importer/tools/gen_contract.py. Do not edit; run",
        "scripts/gen-importer-contract.sh after changing the schemas.",
        '"""',
        "",
        "# The Schema Version these sets come from.",
        f"SCHEMA_MAJOR = {int(version.group(1))}",
        f"SCHEMA_MINOR = {int(version.group(2))}",
        "",
        f"ID_PATTERN = {common['$defs']['id']['pattern']!r}",
        "",
        _tuple("GAMES", common["$defs"]["game"]["enum"]),
        _tuple("EXTENSION_KEYS", list(common["$defs"]["extensions"]["properties"])),
    ]
    for name, file in SETS.items():
        schema = _load(SCHEMA / "sets" / f"{file}.schema.json")
        lines.append("")
        lines.append(f"# {schema['title']}: {schema['description']}")
        lines.append(_tuple(name, schema["enum"]))
        if "x-unique" in schema:
            lines.append(_tuple(f"{name}_UNIQUE", schema["x-unique"], kind="frozenset"))
    return "\n".join(lines) + "\n"


def _tuple(name, values, kind="tuple"):
    open_, close = ("frozenset({", "})") if kind == "frozenset" else ("(", ")")
    if not values:
        return f"{name} = {'frozenset()' if kind == 'frozenset' else '()'}"
    body = "".join(f"    {v!r},\n" for v in values)
    return f"{name} = {open_}\n{body}{close}"


def _load(path):
    with open(path, encoding="utf-8") as f:
        return json.load(f)


def main():
    text = render()
    if "--check" in sys.argv[1:]:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != text:
            print(f"{TARGET.relative_to(REPO)} is out of date; run scripts/gen-importer-contract.sh", file=sys.stderr)
            return 1
        return 0
    TARGET.parent.mkdir(parents=True, exist_ok=True)
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
